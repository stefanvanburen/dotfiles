-- Writes Ghostty themes/<name>-<background> for each of mini.hues' seasonal
-- colorschemes, taking the 16 ANSI colors from the terminal colors mini.hues
-- sets for Nvim's :terminal and the selection from its Visual highlight.
--
-- Run with:
--   nvim --headless -u NONE --cmd 'packadd mini.nvim' -l ~/.config/ghostty/mini-hues.lua
local dir = vim.fs.joinpath(vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':h'), 'themes')
vim.fn.mkdir(dir, 'p')
for _, name in ipairs({ 'minispring', 'minisummer', 'miniautumn', 'miniwinter' }) do
  for _, bg in ipairs({ 'light', 'dark' }) do
    vim.o.background = bg
    vim.cmd.colorscheme(name)
    local p = require('mini.hues').get_palette()
    local lines = {
      string.format('# Generated by ../mini-hues.lua from mini.hues %s (%s).', name, bg),
    }
    for i = 0, 15 do
      table.insert(lines, string.format('palette = %d=%s', i, vim.g['terminal_color_' .. i]))
    end
    vim.list_extend(lines, {
      'background = ' .. p.bg,
      'foreground = ' .. p.fg,
      'selection-background = ' .. p.bg_mid2,
      'selection-foreground = ' .. p.fg,
    })
    vim.fn.writefile(lines, vim.fs.joinpath(dir, name .. '-' .. bg))
  end
end
